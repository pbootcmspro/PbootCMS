<?php

declare(strict_types=1);

/**
 * @suite contract
 * @covers View::parser / View::cache / Config::set / cache_config() 读写 runtime 文件
 *
 * fix #283：编译文件、页面缓存与配置缓存必须原子写入，防止并发请求 include 到空文件或半截文件
 */

if (! defined('TEST_ROOT')) {
    require dirname(__DIR__) . '/bootstrap.php';
}

return TestAssert::runSuite(function () {
    echo "=== View writes compile and page cache files atomically ===\n";

    $view = file_get_contents(CORE_PATH . '/view/View.php');
    TestAssert::false($view === false, 'View.php readable');
    TestAssert::same(2, substr_count($view, 'write_file_atomic($tpl_c_file, $content)'), 'both compile file writes use write_file_atomic');
    TestAssert::same(1, substr_count($view, 'write_file_atomic($cacheFile, $content)'), 'page cache write uses write_file_atomic');
    TestAssert::notContains($view, 'file_put_contents(', 'View has no direct file_put_contents');

    echo "=== Config::set writes config cache atomically ===\n";

    $config = file_get_contents(CORE_PATH . '/basic/Config.php');
    TestAssert::false($config === false, 'Config.php readable');
    TestAssert::contains($config, 'write_file_atomic($path, "<?php', 'Config::set uses write_file_atomic');
    TestAssert::notContains($config, 'file_put_contents(', 'Config has no direct file_put_contents');
    // check_file($path, true) 会先创建空文件，并发读方会 require 到空配置
    TestAssert::notContains($config, 'check_file($path, true)', 'Config::set does not pre-create an empty file');

    echo "=== cache_config injects caches generated by concurrent requests ===\n";

    // 请求启动时缓存尚未生成、随后被并发请求生成时，本请求需补注入，否则缺失数据库配置
    $fn = file_get_contents(APP_PATH . '/common/function.php');
    TestAssert::false($fn === false, 'function.php readable');
    $pos = strpos($fn, 'function cache_config(');
    TestAssert::false($pos === false, 'cache_config() found');
    $next = strpos($fn, "\nfunction ", $pos + 1);
    $body = $next === false ? substr($fn, $pos) : substr($fn, $pos, $next - $pos);
    TestAssert::contains($body, 'Config::assign($config_cache)', 'existing config cache is assigned');
    TestAssert::contains($body, 'Config::assign($lg_cache)', 'existing area cache is assigned');
});
